def gen_multiscan_script(name, step=10.0, stops=10, delay=2.0, subscript=None):
    with open(script_path("%s.script" % name), "w", newline="\n") as f:
        f.write("prefix %s/\n" % name)

        for i in range(stops):
            if i > 0:
                f.write("move %.3f\n" % step)
                f.write("delay %.3f\n" % delay)

            prefix = "%s/position_%.2f/" % (name, i*step)
            f.write("prefix %s\n" % prefix)

            if subscript:
                f.write("subscript %s\n" % subscript)
                f.write("process %s\n" % prefix)
            else:
                f.write("subscript color\n")
                f.write("subscript gray\n")
                if i == stops-1:
                    f.write("subscript mps_32\n")
                    f.write("subscript ulp_10\n")

            f.write("status\n")


