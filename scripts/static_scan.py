patterns_cache = {}


def preload_patterns(path):
    # path is a glob relative to patterns_root, e.g. patterns/<folder>/*
    files = glob.glob(resolve_pattern(path))
    for file in files:
        key = cache_key(file)
        if key in patterns_cache.keys():
            print("Pattern", file, "already loaded!")
        else:
            patterns_cache[key] = cv2.imread(file)[:, :, ::-1]


def first_token(line):
    parts = line.split()
    return parts[0] if parts else ""


def read_script(name):
    # Returns the non-blank, non-comment lines of <scripts_dir>/<name>.script, or None if it does not exist
    filename = script_path("%s.script" % name)
    if not os.path.exists(filename):
        return None
    with open(filename, "r") as f:
        lines = [line.strip() for line in f.readlines()]
    return [line for line in lines if line and line[0] != "#"]


def format_files(files, max_count=10):
    shown = "\n\t\t".join(files[:max_count])
    if len(files) > max_count:
        shown += "\n\t\t... and %d more" % (len(files) - max_count)
    return shown


def check_script(name, lines):
    # Checks that every loaded pattern exists and, for scripts generated by gen_patterns_script, that the script
    # still matches the pattern files the generator would produce now. Returns a list of problems (empty if ok).
    loads = [line.split()[1] for line in lines if first_token(line) == "load" and len(line.split()) > 1]
    problems = []

    missing = [file for file in loads if not os.path.exists(resolve_pattern(file))]
    if missing:
        problems.append("%d loaded file(s) missing on disk:\n\t\t%s" % (len(missing), format_files(missing)))

    if name in pattern_scripts:
        folder = pattern_scripts[name]
        expected = list_pattern_files(folder)
        loads_set, expected_set = set(loads), set(expected)

        extra = [file for file in expected if file not in loads_set]
        if extra:
            problems.append("%d file(s) in patterns/%s not in script:\n\t\t%s" % (len(extra), folder, format_files(extra)))

        foreign = [file for file in loads if file not in expected_set and file not in missing]
        if foreign:
            problems.append("%d loaded file(s) not in patterns/%s:\n\t\t%s" % (len(foreign), folder, format_files(foreign)))

        common_loads = [file for file in loads if file in expected_set]
        common_expected = [file for file in expected if file in loads_set]
        reordered = [a for a, b in zip(common_loads, common_expected) if a != b]
        if reordered:
            problems.append("%d file(s) loaded out of order:\n\t\t%s" % (len(reordered), format_files(reordered)))

    return problems


def load_script(name, ignore_prefix=False, force=False):
    # Reads <scripts_dir>/<name>.script, expanding subscripts (one level), and validates everything before anything
    # is queued. Returns the list of commands to queue, or None if the script should not be run.
    lines = read_script(name)
    if lines is None:
        print(Magenta + "File " + script_path(name + ".script") + " does not exist!" + Reset)
        return None

    commands = []
    scripts = {name: lines}
    for line in lines:
        token = first_token(line)
        if token == "prefix" and ignore_prefix:
            continue
        if token == "subscript":
            parts = line.split()
            if len(parts) < 2:
                print(Magenta + "No subscript name!" + Reset)
                continue
            if parts[1] not in scripts:
                sub_lines = read_script(parts[1])
                if sub_lines is None:
                    print(Red + "Subscript " + script_path(parts[1] + ".script") + " referenced by " + name +
                          " does not exist! Script not queued." + Reset)
                    return None
                scripts[parts[1]] = sub_lines
            commands += [l for l in scripts[parts[1]] if first_token(l) != "prefix"]
            continue
        commands.append(line)

    stale, generated = False, False
    for script_name, script_lines in scripts.items():
        problems = check_script(script_name, script_lines)
        if problems:
            stale = True
            generated = generated or script_name in pattern_scripts
            print(Yellow + "Script %s.script is stale or references missing patterns:" % script_name)
            for problem in problems:
                print("\t" + problem)
            print(Reset, end="")

    if stale:
        if force:
            print(Yellow + "Queuing anyway (force)." + Reset)
        else:
            hint = "Re-run with --generate_scripts to regenerate the scripts, or use" if generated else "Use"
            print(Red + "Script not queued. %s \"script %s force\" to run it anyway." % (hint, name) + Reset)
            return None

    return commands


capture_commands = ["ldr", "hdr"]


def take_command(input_queue, pending, settled):
    # Returns (command to execute now or None, command still pending or None). A capture command (ldr/hdr) stays
    # pending until settled() is true, i.e. the current pattern has been projected for enough frames.
    # The main loop keeps rendering while a command is pending.
    if pending is None:
        if input_queue.empty():
            return None, None
        pending = input_queue.get()
    if first_token(pending) in capture_commands and not settled():
        return None, pending
    return pending, None


def resolve_path(path, base):
    # Relative directories are resolved against base. Returns a path with forward slashes and a trailing "/"
    if not os.path.isabs(path):
        path = os.path.join(base, path)
    path = os.path.normpath(path).replace("\\", "/")
    return path if path.endswith("/") else path + "/"


def load_config(args):
    config_file = os.path.abspath(args.config)
    if not os.path.exists(config_file):
        print(Red + "Config file %s not found." % config_file + Reset)
        print("Copy %s to %s and edit it for this machine, or pass --config PATH." % (example_config, default_config))
        sys.exit(1)

    with open(config_file, "r") as f:
        config = json.load(f)

    missing = [key for key in config_keys if key not in config]
    if missing:
        print(Red + "Config file %s is missing: %s (see %s)" % (config_file, ", ".join(missing), example_config) + Reset)
        sys.exit(1)

    # Relative paths in the config file are relative to the repo root
    for key in ["data_path", "dark_path", "patterns_root", "scripts_dir"]:
        config[key] = resolve_path(config[key], repo_root)
    config["stage"] = config["stage"] or {"type": None}

    # Command line overrides (relative paths are relative to the current directory)
    for key in ["data_path", "dark_path", "patterns_root", "scripts_dir"]:
        if getattr(args, key) is not None:
            config[key] = resolve_path(getattr(args, key), os.getcwd())
    if args.serial_number is not None:
        config["camera_serial"] = args.serial_number
    if args.stage is not None:
        config["stage"]["type"] = None if args.stage == "none" else args.stage
    if args.port is not None:
        config["stage"]["port"] = args.port
    if args.settle_frames is not None:
        config["settle_frames"] = args.settle_frames

    return config


